// Merges the localized fields over the English base object; missing lang/key
// leaves the English object untouched.
export function localizedDeep(table, i18nTable, key, lang) {
  const en = table[key];
  if (!en) return en;
  if (!lang || lang === 'en') return en;
  const t = i18nTable[lang]?.[key];
  if (!t) return en;
  return { ...en, ...t };
}
